// Generates src/lib/territories/seed-data.generated.ts from the pinned
// supabase/seed-data/territory-seed.json. See supabase/seed-data/README.md for provenance.
// The generated module is dynamically imported by the Territory Master "Load default
// India data" CTA and passed to the territory_bulk_seed(...) RPC (migration 103).
// Run: node scripts/generate-territory-seed.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const seed = JSON.parse(readFileSync(resolve(root, 'supabase/seed-data/territory-seed.json'), 'utf8'));

// India-only seed (founder decision, 2026-07-31): only India is preloaded as a
// country. Admins add any other country manually via the tree's "Add Country".
// The full ISO country list stays in territory-seed.json for reference but is not
// seeded.
const countries = [{ n: 'India', c: 'IN' }];
const states = seed.india_states.map((s) => ({ n: s.name, c: s.code }));
const districts = seed.india_districts.map((d) => ({ s: d.state, n: d.name }));

const arr = (rows) => '[\n' + rows.map((r) => '  ' + JSON.stringify(r)).join(',\n') + ',\n]';

const ts = `// GENERATED by scripts/generate-territory-seed.mjs — do not edit by hand.
// Source: supabase/seed-data/territory-seed.json (see that folder's README for pinned provenance).
// Counts: countries=${countries.length}, india_states=${states.length}, india_districts=${districts.length}.
//
// Consumed by the Territory Master empty-state seed CTA, which passes these to the
// territory_bulk_seed(account_id, countries, states, districts) RPC. Kept in its own
// module so it can be dynamically imported (not shipped in the main bundle).

export interface SeedCountry { n: string; c: string | null }
export interface SeedState { n: string; c: string | null }
export interface SeedDistrict { s: string; n: string }

export const SEED_COUNTRIES: SeedCountry[] = ${arr(countries)};

export const SEED_INDIA_STATES: SeedState[] = ${arr(states)};

export const SEED_INDIA_DISTRICTS: SeedDistrict[] = ${arr(districts)};

export const SEED_COUNTS = {
  countries: ${countries.length},
  states: ${states.length},
  districts: ${districts.length},
  total: ${countries.length + states.length + districts.length},
} as const;
`;

mkdirSync(resolve(root, 'src/lib/territories'), { recursive: true });
writeFileSync(resolve(root, 'src/lib/territories/seed-data.generated.ts'), ts);
console.log(`wrote src/lib/territories/seed-data.generated.ts (countries=${countries.length}, states=${states.length}, districts=${districts.length})`);
